/* ============================================================
   Omakase Ship — 共通料金モジュール
   ルート(/) と 料金計算機(/cost/) の両方がこの1ファイルを参照する。
   料金はここだけを書き換えれば両ページに反映される。
   日本郵便 2026年7月・エアパケット100g刻み(〜2kg) / EMS(2kg超)
   ============================================================ */
window.AKIBA_RATES = {
  handling: 1800,   // 取扱手数料（ラベル作成・申告・持込）

  // 梱包の選択肢（材料費と、梱包で増える重量）
  packing: {
    box: { cost:150, addWeight:200 },                 // 段ボール箱
    env: { cost: 50, addWeight: 30, maxGrams: 2000 }  // クッション封筒（2kgまで）
  },
  freeDays: 3,      // 無料保管日数
  perDay:   200,    // 無料日数を超えた1日あたりの保管料

  // 国際エアパケット実費（円）・100g刻み。添字=100g単位（0=〜100g … 19=〜2000g）
  airRates: {
    1: [720,820,920,1020,1120,1220,1320,1420,1520,1620,1720,1820,1920,2020,2120,2220,2320,2420,2520,2620],
    2: [750,870,990,1110,1230,1350,1470,1590,1710,1830,1950,2070,2190,2310,2430,2550,2670,2790,2910,3030],
    3: [880,1060,1240,1420,1600,1780,1960,2140,2320,2500,2680,2860,3040,3220,3400,3580,3760,3940,4120,4300],
    4: [1200,1410,1620,1830,2040,2250,2460,2670,2880,3090,3300,3510,3720,3930,4140,4350,4560,4770,4980,5190]
  },
  // 2kg超はEMS実費（円）
  emsSteps: [2000,2500,3000,3500,4000,4500,5000],
  emsRates: {
    1: [3400,3900,4400,4900,5400,5900,6400],
    2: [4550,5150,5750,6350,6950,7550,8150],
    3: [6700,7750,8800,9850,10900,11950,13000],
    4: [7900,9100,10300,11500,12700,13900,15100]
  },

  // 実重量(g)から送料を返す。{yen, svc} または null（0以下 / 上限超）
  postage: function(zone, grams){
    if(grams<=0) return null;
    if(grams<=2000){
      var i = Math.ceil(grams/100)-1;
      return { yen: this.airRates[zone][i], svc:"Air Packet" };
    }
    for(var k=0;k<this.emsSteps.length;k++){
      if(grams<=this.emsSteps[k]) return { yen: this.emsRates[zone][k], svc:"EMS" };
    }
    return null;
  }
};

/* Node(検証スクリプト)からも読めるようにする。ブラウザには影響しない。 */
if (typeof module !== "undefined" && module.exports) module.exports = window.AKIBA_RATES;
